export function useI18n() {
  const language = useContext(I18nContext)
  return {
    language,
    t: (key: string, variables?: Record<string, string | number>) => translate(language, key, variables),
    name: (value: string) => localizeName(language, value),
    description: (id: string, fallback: string) => localizeDescription(language, id, fallback),
    status: (value: StatusEffectType) => localizeStatus(language, value),
    log: (value: string) => localizeLog(language, value),
  }
}
